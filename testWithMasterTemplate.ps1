# This script is used to test the master template with the standard library. 
# It will pack the standard library, update the master template with the new version, and build the master template.

# Usage: .\testWithMasterTemplate.ps1 [-MasterTemplateDirectory "C:\path\to\bsi-cx-design-master-template-web"]

# For signing the script follow the instructions here: https://bsiag.sharepoint.com/sites/Intra-IT/SitePages/CodeSigning.aspx

param(
    [string]$MasterTemplateDirectory = "..\bsi-cx-design-master-template-web"
)

$ErrorActionPreference = 'Stop'

try {
    # pack this library
    npm pack --pack-destination $MasterTemplateDirectory
    if ($LASTEXITCODE -ne 0) {
        throw "npm pack ist fehlgeschlagen (Exitcode $LASTEXITCODE)."
    }

    # Go to Master Template, update Standard library and build
    Push-Location -LiteralPath $MasterTemplateDirectory
    try {
        npm update @bsi-cx/design-standard-library-web
        if ($LASTEXITCODE -ne 0) {
            throw "npm update ist fehlgeschlagen (Exitcode $LASTEXITCODE)."
        }

        npm run build:dev
        if ($LASTEXITCODE -ne 0) {
            throw "Der Build ist fehlgeschlagen (Exitcode $LASTEXITCODE)."
        }
    }
    finally {
        Pop-Location
    }
}
finally {
    Pop-Location
}

